  // Delete project
  static deleteProject(projectId: string): void {
    try {
      const savedProjects = localStorage.getItem('techarket-projects');
      if (savedProjects) {
        const projects = JSON.parse(savedProjects);
        const updatedProjects = projects.filter((p: any) => p.id !== projectId);
        localStorage.setItem('techarket-projects', JSON.stringify(updatedProjects));
      }
    } catch (error) {
      console.error('Failed to delete project:', error);
    }
  }

  // Update project
  static updateProject(project: LocalProject): void {
    try {
      const savedProjects = localStorage.getItem('techarket-projects');
      if (savedProjects) {
        const projects = JSON.parse(savedProjects);
        const updatedProjects = projects.map((p: any) => 
          p.id === project.id ? { ...project, lastModified: new Date() } : p
        );
        localStorage.setItem('techarket-projects', JSON.stringify(updatedProjects));
      }
    } catch (error) {
      console.error('Failed to update project:', error);
    }
  }
