  private static extractFilenameFromContent(content: string, language: string): string | null {
    // Try to extract filename from comments
    const commentPatterns = [
      /\/\/ @filename: (.+)/,
      /\/\* @filename: (.+) \*\//,
      /# @filename: (.+)/,
      /<!-- @filename: (.+) -->/
    ];

    for (const pattern of commentPatterns) {
      const match = content.match(pattern);
      if (match) {
        return match[1].trim();
      }
    }

    // Try to extract component name from React components
    if (language === 'typescript' || language === 'tsx') {
      const componentMatch = content.match(/(?:export\s+(?:default\s+)?(?:function|const)\s+|function\s+)(\w+)/);
      if (componentMatch) {
        return `${componentMatch[1]}.tsx`;
      }
    }

    return null;
  }

