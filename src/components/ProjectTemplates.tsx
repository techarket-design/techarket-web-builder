interface ProjectTemplatesProps {
  onSelectTemplate: (template: ProjectTemplate) => void;
}

export const ProjectTemplates: React.FC<ProjectTemplatesProps> = ({ onSelectTemplate }) => {
  const getTemplateIcon = (type: string) => {
    switch (type) {
      case 'react': return <Code className="text-blue-400" size={20} />;
      case 'next': return <Globe className="text-black" size={20} />;
      case 'vue': return <Zap className="text-green-400" size={20} />;
      case 'express': return <Server className="text-yellow-400" size={20} />;
      case 'python': return <Database className="text-blue-500" size={20} />;
      case 'vanilla': return <Smartphone className="text-purple-400" size={20} />;
      default: return <Code className="text-gray-400" size={20} />;
    }
  };

  return (
    <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
      {projectTemplates.map((template) => (
        <div
          key={template.id}
          onClick={() => onSelectTemplate(template)}
          className="bg-gray-800 border border-gray-700 rounded-lg p-4 cursor-pointer hover:border-blue-500 transition-colors"
        >
          <div className="flex items-center space-x-3 mb-3">
            {getTemplateIcon(template.type)}
            <h3 className="font-medium text-gray-200">{template.name}</h3>
          </div>
          <p className="text-sm text-gray-400 mb-4">{template.description}</p>
          <div className="flex items-center justify-between text-xs text-gray-500">
            <span>Port: {template.port}</span>
            <span>{template.dependencies.length + template.devDependencies.length} deps</span>
          </div>
        </div>
      ))}
    </div>
  );
};